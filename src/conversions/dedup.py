"""Дедупликация событий между браузерным Pixel и серверным CAPI.

Правило: одно и то же логическое событие (например, отправка формы) должно
уйти и из браузера (fbq('track', 'Lead', {...}, {eventID: ...})), и с сервера
(CAPI) с ОДИНАКОВЫМ event_id. Meta схлопнет дубликат по паре
(event_name, event_id).
"""

from __future__ import annotations

import uuid


def new_event_id() -> str:
    """Сгенерировать новый уникальный event_id.

    Обычно генерируется на фронте и прокидывается на сервер, чтобы обе стороны
    отправили одинаковое значение. Здесь — на случай, когда событие рождается
    на сервере (например, лид из webhook).
    """
    return uuid.uuid4().hex
